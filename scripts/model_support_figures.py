def component_of(path):
    """Map a repository file to the component it belongs to."""
    rel = path.relative_to(REPO_ROOT).as_posix()
    if rel.startswith("src/lrcs/"):
        parts = rel[len("src/lrcs/"):].split("/")
        if len(parts) == 1:
            stem = parts[0][:-3]
            return "lrcs" if stem == "__init__" else f"lrcs.{stem}"
        return f"lrcs.{parts[0]}"
    if rel.startswith("common/"):
        return "common/repro"
    return rel.split("/")[0] + "/"


def package_of(path, root=None):
    """Dotted package of a file under src/, e.g. src/lrcs/data/x.py -> lrcs.data."""
    root = root or REPO_ROOT
    rel = path.relative_to(root)
    if rel.parts[:1] != ("src",):
        return None
    return ".".join(rel.parts[1:-1])


def resolve_import(module, names, level, package):
    """Return the internal component an import refers to, or None.

    `package` is the importing file's dotted package; it is only used to resolve
    relative imports (`from ..text import x` inside lrcs.data -> lrcs.text).
    """
    if level:
        if not package:
            return None
        parts = package.split(".")
        base = ".".join(parts[:len(parts) - (level - 1)])
        module = f"{base}.{module}" if module else base
    if module is None:
        return None
    if module in ("repro", "run_contract"):   # both live in common/, imported by bare name
        return "common/repro"
    if module == "lrcs":
        # `from lrcs import text` names a submodule; `from lrcs import REPO_ROOT` the core
        subs = [n for n in names if n in ("text", "lexicon", "data", "analysis", "warehouse")]
        return f"lrcs.{subs[0]}" if subs else "lrcs"
    if module.startswith("lrcs."):
        return "lrcs." + module.split(".")[1]
    return None


def scan_imports(root=REPO_ROOT):
    """Return (internal edges, third-party use, files per component)."""
    edges = defaultdict(set)      # (src, dst) -> files
    external = defaultdict(set)   # (component, package) -> files
    files = defaultdict(list)
    for d in SCAN:
        for path in sorted((root / d).rglob("*.py")):
            if "__pycache__" in path.parts:
                continue
            comp = component_of(path)
            pkg = package_of(path, root)
            rel = path.relative_to(root).as_posix()
            files[comp].append(rel)
            try:
                tree = ast.parse(path.read_text(encoding="utf-8"))
            except SyntaxError:
                continue
            for node in ast.walk(tree):
                if isinstance(node, ast.ImportFrom):
                    names = [a.name for a in node.names]
                    dst = resolve_import(node.module, names, node.level, pkg)
                    top = (node.module or "").split(".")[0]
                elif isinstance(node, ast.Import):
                    dst, top = None, None
                    for a in node.names:
                        d2 = resolve_import(a.name, [], 0, pkg)
                        if d2 and d2 != comp:
                            edges[(comp, d2)].add(rel)
                        t = a.name.split(".")[0]
                        if t in THIRD_PARTY:
                            external[(comp, THIRD_PARTY[t])].add(rel)
                    continue
                else:
                    continue
                if dst and dst != comp:
                    edges[(comp, dst)].add(rel)
                if top in THIRD_PARTY:
                    external[(comp, THIRD_PARTY[top])].add(rel)
    return edges, external, files


