# ------------------------------------------------------------------ drawing helpers


def _box(ax, x, y, w, h, text, fill=FILL_GIT, dashed=False, edge=TEXT_SECONDARY,
         size=7.5, bold=False):
    from matplotlib.patches import FancyBboxPatch
    ax.add_patch(FancyBboxPatch(
        (x, y), w, h, boxstyle="round,pad=0.006,rounding_size=0.012",
        linewidth=1.1, edgecolor=edge, facecolor=fill,
        linestyle=(0, (4, 3)) if dashed else "solid", zorder=2))
    ax.text(x + w / 2, y + h / 2, text, ha="center", va="center", fontsize=size,
            color=TEXT_PRIMARY, zorder=3, linespacing=1.25,
            fontweight="bold" if bold else "normal")
    return (x, y, w, h)


def _zone(ax, x, y, w, h, title, dashed=False):
    from matplotlib.patches import FancyBboxPatch
    ax.add_patch(FancyBboxPatch(
        (x, y), w, h, boxstyle="round,pad=0.004,rounding_size=0.015",
        linewidth=1.0, edgecolor=GRID if not dashed else TEXT_SECONDARY,
        facecolor=FILL_ZONE, linestyle=(0, (4, 3)) if dashed else "solid", zorder=1))
    ax.text(x + 0.012, y + h - 0.012, title, ha="left", va="top", fontsize=8.5,
            color=TEXT_PRIMARY, fontweight="bold", zorder=3)


def _anchor(box, side):
    x, y, w, h = box
    return {"l": (x, y + h / 2), "r": (x + w, y + h / 2),
            "t": (x + w / 2, y + h), "b": (x + w / 2, y)}[side]


def _arrow(ax, a, b, label=None, color=TEXT_SECONDARY, dashed=False, rad=0.0,
           label_at=0.5, label_dy=0.012, size=6.5):
    ax.annotate("", xy=b, xytext=a, zorder=4,
                arrowprops=dict(arrowstyle="-|>", color=color, lw=1.0,
                                shrinkA=2, shrinkB=2, mutation_scale=9,
                                linestyle=(0, (4, 3)) if dashed else "solid",
                                connectionstyle=f"arc3,rad={rad}"))
    if label:
        mx = a[0] + (b[0] - a[0]) * label_at
        my = a[1] + (b[1] - a[1]) * label_at + label_dy
        ax.text(mx, my, label, ha="center", va="bottom", fontsize=size,
                color=TEXT_SECONDARY, zorder=5,
                bbox=dict(boxstyle="round,pad=0.15", fc=SURFACE, ec="none", alpha=0.9))


def _legend(ax, x, y):
    from matplotlib.lines import Line2D
    from matplotlib.patches import Patch
    handles = [
        Patch(facecolor=FILL_GIT, edgecolor=TEXT_SECONDARY, label="exists on main and has executed"),
        Patch(facecolor=FILL_GIT, edgecolor=TEXT_SECONDARY, linestyle="--",
              label="planned or unconfirmed"),
        Patch(facecolor=FILL_LOCAL, edgecolor=TEXT_SECONDARY,
              label="not version-controlled"),
        Line2D([0], [0], color=SERIES_1, lw=1.4, label="committed evidence path"),
    ]
    ax.legend(handles=handles, loc="lower left", bbox_to_anchor=(x, y), fontsize=6.5,
              frameon=False, ncol=4, handlelength=1.6, columnspacing=1.2)


def _canvas(width, height, title, subtitle):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig = plt.figure(figsize=(width, height), dpi=200)
    fig.patch.set_facecolor(SURFACE)
    ax = fig.add_axes([0, 0, 1, 1])
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1)
    ax.axis("off")
    ax.text(0.02, 0.975, title, ha="left", va="top", fontsize=11, color=TEXT_PRIMARY)
    ax.text(0.02, 0.94, subtitle, ha="left", va="top", fontsize=7.5, color=TEXT_SECONDARY)
    return fig, ax


def _save(fig, path):
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, facecolor=SURFACE, metadata={"Software": None})
    import matplotlib.pyplot as plt
    plt.close(fig)
    return path


