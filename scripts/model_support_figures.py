def draw_components(out, json_out):
    edges, external, files = scan_imports()
    fig, ax = _canvas(11, 6.8, "Figure 4.2.3  Component dependencies",
                      "Computed from the import statements on this commit by "
                      "scripts/model_support_figures.py. Edge label = number of importing files.")
    w, h = 0.15, 0.10
    boxes = {}
    for comp, (cx, cy) in LAYOUT.items():
        if comp not in files:
            continue
        n = len(files[comp])
        ext = sorted({pkg for (c, pkg) in external if c == comp})
        label = f"{comp}\n{ROLE.get(comp, '')}\n{n} file{'s' if n != 1 else ''}"
        boxes[comp] = _box(ax, cx - w / 2, cy - h / 2, w, h, label, size=6.8,
                           edge=SERIES_1 if comp == "common/repro" else TEXT_SECONDARY)
        if ext:
            lines = [", ".join(ext[i:i + 3]) for i in range(0, len(ext), 3)]
            ax.text(cx, cy - h / 2 - 0.01, "\n".join(lines), ha="center", va="top",
                    fontsize=5.8, color=SERIES_2, style="italic")

    root_users = []
    for (src, dst), fs in sorted(edges.items()):
        if dst == ROOT_BAR:
            root_users.append(f"{src} {len(fs)}")
            continue
        if src not in boxes or dst not in boxes:
            continue
        sx, sy = LAYOUT[src]
        dx, dy = LAYOUT[dst]
        if abs(sy - dy) < 1e-9:   # same row: side to side
            a, b = (_anchor(boxes[src], "l"), _anchor(boxes[dst], "r")) if sx > dx else \
                   (_anchor(boxes[src], "r"), _anchor(boxes[dst], "l"))
        else:
            a, b = _anchor(boxes[src], "b"), _anchor(boxes[dst], "t")
        color = SERIES_1 if dst == "common/repro" else TEXT_SECONDARY
        rad = EDGE_RAD.get((src, dst), 0.0)
        _arrow(ax, a, b, None, color=color, rad=rad)
        if rad:   # a curved edge's midpoint is off the chord; label it at its source end
            ax.text(a[0] - 0.035, a[1] - 0.06, str(len(fs)), fontsize=6, color=TEXT_SECONDARY,
                    ha="center", bbox=dict(boxstyle="round,pad=0.15", fc=SURFACE, ec="none"))
        else:
            mx, my = a[0] + (b[0] - a[0]) * 0.62, a[1] + (b[1] - a[1]) * 0.62
            ax.text(mx, my, str(len(fs)), fontsize=6, color=TEXT_SECONDARY, ha="center",
                    va="center", zorder=5,
                    bbox=dict(boxstyle="round,pad=0.15", fc=SURFACE, ec="none"))

    if ROOT_BAR in files:
        _box(ax, 0.30, 0.075, 0.66, 0.06,
             f"lrcs  (package root: REPO_ROOT, repo_relative)  imported by  "
             + ",  ".join(root_users), size=6.6)

    ax.text(0.015, 0.825, "entry points", fontsize=7.5, color=TEXT_SECONDARY, style="italic")
    ax.text(0.015, 0.575, "library", fontsize=7.5, color=TEXT_SECONDARY, style="italic")
    ax.text(0.015, 0.335, "foundations", fontsize=7.5, color=TEXT_SECONDARY, style="italic")
    ax.text(0.02, 0.04,
            "Orange = third-party packages imported by that component. Blue edges reach "
            "common/repro, the single seeding and run-logging path every run goes through.",
            fontsize=7, color=TEXT_SECONDARY, ha="left", va="top")

    record = {
        "generated_by": "scripts/model_support_figures.py",
        "components": {c: sorted(f) for c, f in sorted(files.items())},
        "edges": [{"from": s, "to": d, "files": sorted(f)} for (s, d), f in sorted(edges.items())],
        "third_party": [{"component": c, "package": p, "files": sorted(f)}
                        for (c, p), f in sorted(external.items())],
    }
    json_out.write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8")
    return _save(fig, out), record


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out-dir", default=str(REPO_ROOT / "reports" / "figures"))
    ap.add_argument("--check", action="store_true",
                    help="fail if a component in the repository has no place in the layout")
    args = ap.parse_args(argv)
    out = Path(args.out_dir)

    print("figure ->", draw_lineage(out / FIGURES["lineage"]))
    print("figure ->", draw_platform(out / FIGURES["platform"]))
    print("figure ->", draw_dataflow(out / FIGURES["dataflow"]))
    path, record = draw_components(out / FIGURES["components"], out / COMPONENTS_JSON)
    print("figure ->", path)
    print("edges  ->", out / COMPONENTS_JSON)
    for e in record["edges"]:
        print(f"  {e['from']:<14} -> {e['to']:<14} {len(e['files'])} file(s)")

    unplaced = sorted(set(record["components"]) - set(LAYOUT) - {ROOT_BAR})
    if unplaced:
        msg = "components with no place in the layout: " + ", ".join(unplaced)
        if args.check:
            sys.exit(msg)
        print("warning:", msg, file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
